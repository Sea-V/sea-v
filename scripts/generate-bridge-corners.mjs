#!/usr/bin/env node
/**
 * Bridge theme (v581): square every rounded corner on the signed-in pages.
 *
 * Reads the stylesheets the app pages use, collects every selector whose
 * rule sets a rounded border-radius (6px and up, or 999px pills), and writes
 * them into the GENERATED block of css/core/theme-bridge.css as one
 * `body.app-page :is(...)` rule. True circles (50%) are left alone —
 * avatars, colour dots, step markers. Pseudo-elements are skipped (they are
 * not allowed inside :is()); selectors that start at body/html are skipped
 * because they cannot sit under body.app-page.
 *
 * Run after changing any page stylesheet:
 *   node scripts/generate-bridge-corners.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

// Public-only pages are excluded: the theme only applies to body.app-page.
const SKIP = new Set([
  "public-profile.css", "index.css", "signup.css", "auth.css", "info.css",
  "legal.css", "verify-reference.css", "confirm-account.css", "reset-password.css",
  "landing-brand.css", "ocean-background.css"
]);

const files = [
  ...fs.readdirSync(path.join(root, "css/pages")).map((f) => `css/pages/${f}`),
  ...fs.readdirSync(path.join(root, "css/components")).map((f) => `css/components/${f}`),
  "css/core/layout.css",
  "css/core/typography.css"
].filter((f) => f.endsWith(".css") && !SKIP.has(path.basename(f)));

function rounded(value) {
  const v = value.trim().replace(/!important/, "").trim();
  if (/^50%$/.test(v)) return false;
  if (/var\(--bridge/.test(v)) return false;
  // Any length of 6px or more (or a var we cannot resolve that is not a
  // known circle) counts as rounded.
  const px = [...v.matchAll(/(\d+(?:\.\d+)?)px/g)].map((m) => Number(m[1]));
  if (px.some((n) => n >= 6)) return true;
  if (/var\(--/.test(v) && !/50%/.test(v)) return true;
  return false;
}

const selectors = new Set();
for (const file of files) {
  const css = fs.readFileSync(path.join(root, file), "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
  // Naive but sufficient: every "selector { declarations }" pair, at any depth.
  for (const m of css.matchAll(/([^{}@;]+)\{([^{}]*)\}/g)) {
    const decls = m[2];
    const radius = /(?:^|;|\s)border(?:-(?:top|bottom)-(?:left|right))?-radius\s*:\s*([^;]+)/i.exec(decls);
    if (!radius || !rounded(radius[1])) continue;
    for (let sel of m[1].split(",")) {
      sel = sel.trim().replace(/\s+/g, " ");
      // Rules already scoped to app pages: keep them, minus the scope.
      sel = sel.replace(/^body\.app-page(\[[^\]]*\])*\s+/, "");
      if (!sel || sel.includes("::") || /:(before|after)\b/.test(sel)) continue;
      if (/^(html|body)\b/.test(sel) || sel.startsWith(":root") || /^\d/.test(sel) || sel.startsWith("from") || sel.startsWith("to")) continue;
      if (/leaflet|cvgen-preview|cv-doc|cv-page|seav-version-badge/.test(sel)) continue;
      // Meant to stay round: avatars, the badge-unlock celebration, toggle
      // switches and the loading animation.
      if (/avatar|badge-unlock|switch|loader|knob/.test(sel)) continue;
      selectors.add(sel);
    }
  }
}

const list = [...selectors].sort();
const block = [
  "/* GENERATED by scripts/generate-bridge-corners.mjs — do not edit by hand.",
  `   ${list.length} selectors from the app-page stylesheets that set a rounded corner. */`,
  "body.app-page :is(",
  list.map((s) => `  ${s}`).join(",\n"),
  ") {",
  "  border-radius: var(--bridge-radius) !important;",
  "}"
].join("\n");

const target = path.join(root, "css/core/theme-bridge.css");
const raw = fs.readFileSync(target, "utf8");
const START = "/* >>> GENERATED CORNERS >>> */";
const END = "/* <<< GENERATED CORNERS <<< */";
const next = raw.includes(START)
  ? raw.replace(new RegExp(`${START.replace(/[*/]/g, "\\$&")}[\\s\\S]*?${END.replace(/[*/]/g, "\\$&")}`), `${START}\n${block}\n${END}`)
  : `${raw.trimEnd()}\n\n${START}\n${block}\n${END}\n`;
fs.writeFileSync(target, next);
console.log(`Bridge corners: ${list.length} selectors written to css/core/theme-bridge.css`);
